package Aula061404AssociacaoAgregacaoEComposicao.composicao;

public class Bola {
    private String marcaDaBola;
    private String nomeDaBola;

    public Bola(String marcaDaBola, String nomeDaBola) {
        this.marcaDaBola = marcaDaBola;
        this.nomeDaBola = nomeDaBola;
    }

    public String getMarcaDaBola() {
        return marcaDaBola;
    }

    public String getNomeDaBola() {
        return nomeDaBola;
    }
}
